// Regenerates hooks/vendor/dagre.mjs: @dagrejs/dagre (with graphlib) as one minified ESM file.
// Run: node plugins/how/scripts/vendor-dagre.mjs   (needs `npm install` in plugins/how first)
import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
await build({
  stdin: { contents: `import dagre from '@dagrejs/dagre'\nexport default dagre\n`, resolveDir: root, loader: 'js' },
  outfile: join(root, 'hooks/vendor/dagre.mjs'),
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  mainFields: ['module', 'main'],
  target: 'es2022',
  minify: true,
  legalComments: 'none',
  banner: { js: '/* Generated by scripts/vendor-dagre.mjs from @dagrejs/dagre. Do not edit. */' },
})
